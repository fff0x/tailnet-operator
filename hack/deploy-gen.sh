#!/usr/bin/env bash
# Render without a kubeconfig or cluster access. --check never changes tracked files.
set -euo pipefail
cd "$(dirname "$0")/.."
mode="${1:-write}"
[[ "$mode" == write || "$mode" == --check ]] || { echo 'Usage: deploy-gen.sh [--check]' >&2; exit 2; }
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
{
  printf '# GENERATED by task deploy-gen — edit the chart, not this file.\n'
  printf '%s\n' '---' 'apiVersion: v1' 'kind: Namespace' 'metadata:' '  name: tailnet-system'
  # Helm 4 adds blank lines between resources that Helm 3 omits. Normalize only
  # document-boundary whitespace in this default bundle (no literal data blocks).
  helm template tailnet-operator charts/tailnet-operator --namespace tailnet-system --kube-version 1.31.0 |
    awk '/^[[:space:]]*$/ { blank = blank $0 ORS; next }
         /^---$/ { blank = "" }
         { printf "%s", blank; blank = ""; print }'
} > "$tmp/operator.yaml"
if [[ "$mode" == --check ]]; then
  diff -u deploy/operator.yaml "$tmp/operator.yaml"
else
  cp "$tmp/operator.yaml" deploy/operator.yaml
fi
