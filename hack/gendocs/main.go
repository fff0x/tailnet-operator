// Command gendocs renders docs/reference/crds.md from deploy/crds/*.yaml: one section per kind
// with scope, version and a flattened field table (path, type, required, description) for spec
// and status, read from openAPIV3Schema. The golden test in this package fails when the checked-in
// page drifts from the CRDs; `task docs` regenerates it.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"sigs.k8s.io/yaml"
)

const header = `---
title: "CRD reference"
weight: 10
description: "Every field of Tailnet, TailnetEgress, TailnetIngress, TailnetSite, TailnetGrant and TailnetGateway with type, requirement, default and description, generated from the CRD schemas."
---

<!-- Generated by hack/gendocs from deploy/crds; edit the Go types or their markers, not this file. -->

Field tables are rendered from the installed CRD schemas (` + "`deploy/crds/*.yaml`" + `); the worked
examples live in the how-to guides. Admission rules beyond the schema (CEL) are summarised in
[Validation](../operations/validation.md); condition reasons in [Reasons](reasons.md).

`

func main() {
	root := "."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	out, err := Render(filepath.Join(root, "deploy", "crds"))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	target := filepath.Join(root, "docs", "reference", "crds.md")
	if err := os.WriteFile(target, []byte(out), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

type crd struct {
	Spec struct {
		Scope string `json:"scope"`
		Names struct {
			Kind       string   `json:"kind"`
			Plural     string   `json:"plural"`
			ShortNames []string `json:"shortNames"`
		} `json:"names"`
		Versions []struct {
			Name   string `json:"name"`
			Schema struct {
				OpenAPIV3Schema schema `json:"openAPIV3Schema"`
			} `json:"schema"`
		} `json:"versions"`
	} `json:"spec"`
}

type schema struct {
	Description string            `json:"description"`
	Type        string            `json:"type"`
	Format      string            `json:"format"`
	Required    []string          `json:"required"`
	Properties  map[string]schema `json:"properties"`
	Items       *schema           `json:"items"`
	Enum        []any             `json:"enum"`
	Default     any               `json:"default"`
	Minimum     *float64          `json:"minimum"`
	Maximum     *float64          `json:"maximum"`
	MinItems    *int              `json:"minItems"`
	MaxItems    *int              `json:"maxItems"`
	MaxLength   *int              `json:"maxLength"`
	Pattern     string            `json:"pattern"`
}

// Render returns the whole Markdown page for every CRD in dir, kinds sorted by name.
func Render(dir string) (string, error) {
	files, err := filepath.Glob(filepath.Join(dir, "*.yaml"))
	if err != nil {
		return "", err
	}
	if len(files) == 0 {
		return "", fmt.Errorf("no CRDs in %s", dir)
	}
	var kinds []crd
	for _, f := range files {
		raw, err := os.ReadFile(f)
		if err != nil {
			return "", err
		}
		var c crd
		if err := yaml.Unmarshal(raw, &c); err != nil {
			return "", fmt.Errorf("%s: %w", f, err)
		}
		if len(c.Spec.Versions) == 0 {
			return "", fmt.Errorf("%s: no versions", f)
		}
		kinds = append(kinds, c)
	}
	sort.Slice(kinds, func(i, j int) bool { return kinds[i].Spec.Names.Kind < kinds[j].Spec.Names.Kind })

	var b strings.Builder
	b.WriteString(header)
	for _, c := range kinds {
		for _, v := range c.Spec.Versions {
			root := v.Schema.OpenAPIV3Schema
			fmt.Fprintf(&b, "## %s\n\n", c.Spec.Names.Kind)
			fmt.Fprintf(&b, "`%s.%s` · scope **%s** · short name", c.Spec.Names.Plural, "tsunaro.io", c.Spec.Scope)
			if len(c.Spec.Names.ShortNames) == 0 {
				b.WriteString(" —")
			} else {
				fmt.Fprintf(&b, " `%s`", strings.Join(c.Spec.Names.ShortNames, "`, `"))
			}
			fmt.Fprintf(&b, " · `%s`\n\n", v.Name)
			if d := oneLine(root.Description); d != "" {
				b.WriteString(d + "\n\n")
			}
			for _, section := range []string{"spec", "status"} {
				s, ok := root.Properties[section]
				if !ok {
					continue
				}
				fmt.Fprintf(&b, "### %s\n\n", strings.ToUpper(section[:1])+section[1:])
				if d := oneLine(s.Description); d != "" {
					b.WriteString(d + "\n\n")
				}
				b.WriteString("| Field | Type | Required | Description |\n| --- | --- | --- | --- |\n")
				writeRows(&b, "", s)
				b.WriteString("\n")
			}
		}
	}
	return b.String(), nil
}

func writeRows(b *strings.Builder, prefix string, s schema) {
	required := map[string]bool{}
	for _, r := range s.Required {
		required[r] = true
	}
	names := make([]string, 0, len(s.Properties))
	for n := range s.Properties {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		p := s.Properties[n]
		path := prefix + n
		child := p
		typ := p.Type
		if p.Type == "array" && p.Items != nil {
			path += "[]"
			child = *p.Items
			typ = "[]" + p.Items.Type
		}
		req := "no"
		if required[n] {
			req = "yes"
		}
		fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", path, typ, req, cell(p))
		if len(child.Properties) > 0 {
			writeRows(b, path+".", child)
		}
	}
}

// cell is the description plus the machine-readable constraints that matter to a writer.
func cell(p schema) string {
	parts := []string{}
	if d := oneLine(p.Description); d != "" {
		parts = append(parts, d)
	}
	var extra []string
	if p.Default != nil {
		extra = append(extra, fmt.Sprintf("Default `%v`.", p.Default))
	}
	if len(p.Enum) > 0 {
		vals := make([]string, len(p.Enum))
		for i, e := range p.Enum {
			vals[i] = fmt.Sprintf("`%v`", e)
		}
		extra = append(extra, "One of "+strings.Join(vals, ", ")+".")
	}
	if p.Minimum != nil || p.Maximum != nil {
		extra = append(extra, rangeText("Range", p.Minimum, p.Maximum))
	}
	if p.MinItems != nil || p.MaxItems != nil {
		extra = append(extra, rangeTextInt("Items", p.MinItems, p.MaxItems))
	}
	if p.MaxLength != nil {
		extra = append(extra, fmt.Sprintf("Max length %d.", *p.MaxLength))
	}
	if p.Format != "" {
		extra = append(extra, "Format `"+p.Format+"`.")
	}
	if len(extra) > 0 {
		parts = append(parts, strings.Join(extra, " "))
	}
	return strings.Join(parts, " ")
}

func rangeText(label string, lo, hi *float64) string {
	switch {
	case lo != nil && hi != nil:
		return fmt.Sprintf("%s %v–%v.", label, *lo, *hi)
	case lo != nil:
		return fmt.Sprintf("%s ≥ %v.", label, *lo)
	default:
		return fmt.Sprintf("%s ≤ %v.", label, *hi)
	}
}

func rangeTextInt(label string, lo, hi *int) string {
	switch {
	case lo != nil && hi != nil:
		return fmt.Sprintf("%s %d–%d.", label, *lo, *hi)
	case lo != nil:
		return fmt.Sprintf("%s ≥ %d.", label, *lo)
	default:
		return fmt.Sprintf("%s ≤ %d.", label, *hi)
	}
}

// oneLine collapses a schema description into one table-safe line.
func oneLine(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.ReplaceAll(s, "|", "\\|")
}
